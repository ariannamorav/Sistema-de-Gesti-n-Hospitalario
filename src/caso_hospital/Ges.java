    private void registrosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrosActionPerformed
        CLASSX CD = new CLASSX();

        ArrayList<String> registros = CD.obtenerRegistrosTratamientos();

        if (registros == null || registros.isEmpty()) {
            JOptionPane.showMessageDialog(null, "No se encontraron registros de tratamientos.", "Registros", JOptionPane.INFORMATION_MESSAGE);
        } else {
            StringBuilder sb = new StringBuilder();
            sb.append("Registros de Tratamientos:\n");
            for (String registro : registros) {
                sb.append(registro).append("\n");
            }
            JOptionPane.showMessageDialog(null, sb.toString(), "Registros de Tratamientos", JOptionPane.INFORMATION_MESSAGE);
        }

        ArrayList<String> registrosTratamientos = CD.obtenerPacientesTratamientos();
        if (registrosTratamientos == null || registrosTratamientos.isEmpty()) {
            JOptionPane.showMessageDialog(null, "No se encontraron registros de pacientes con tratamientos.", "Registros", JOptionPane.INFORMATION_MESSAGE);
        } else {
            StringBuilder sb = new StringBuilder();
            sb.append("Pacientes con Tratamientos:\n");
            for (String registro : registrosTratamientos) {
                sb.append(registro).append("\n");
            }
            JOptionPane.showMessageDialog(null, sb.toString(), "Pacientes con Tratamientos", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_registrosActionPerformed

