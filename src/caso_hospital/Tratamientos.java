    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

    
    if (jTextField1.getText().isEmpty() || jTextField2.getText().isEmpty() || 
        jTextArea1.getText().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Todos los campos deben estar llenos", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    CLASSX CD = new CLASSX(); 
        
    try {
        int idtrat = Integer.parseInt(jTextField1.getText());
        int id_P = Integer.parseInt(jTextField2.getText());

        if (!CD.validarIdPaciente(id_P)) {
            JOptionPane.showMessageDialog(null, "El ID del paciente no existe", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        CD.insertarTratamiento(idtrat, jTextArea1.getText());
        JOptionPane.showMessageDialog(null, "Tratamiento registrado correctamente.");

        CD.insertarPacienteTratamiento(id_P, idtrat);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "El ID del tratamiento debe ser numérico", "Error", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_jButton1ActionPerformed

    
