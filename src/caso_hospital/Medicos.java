    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    if (jTextField1.getText().isEmpty() || jTextField2.getText().isEmpty() || 
        jTextField3.getText().isEmpty() || jTextField4.getText().isEmpty()) {
        
        JOptionPane.showMessageDialog(null, "Todos los campos deben estar llenos", "Error", JOptionPane.ERROR_MESSAGE);
        return; 
    }
    
    // Validar que el ID sea numérico
    try {
        int idMedico = Integer.parseInt(jTextField1.getText());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "El ID del médico debe ser numérico", "Error", JOptionPane.ERROR_MESSAGE);
        return; // Se sale del método si el ID no es válido
    }

    // Validar que el nombre contenga solo letras
    if (!jTextField2.getText().matches("[a-zA-Z\\s]+")) {
        JOptionPane.showMessageDialog(null, "El nombre solo puede contener letras", "Error", JOptionPane.ERROR_MESSAGE);
        return; 
    }
    
    CLASSX CD = new CLASSX();
    try {
        CD.insertarMedico(Integer.parseInt(jTextField1.getText()), jTextField2.getText(), jTextField3.getText(), jTextField4.getText());
        JOptionPane.showMessageDialog(null, "Médico registrado con éxito");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error al registrar el médico: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

