    private void registrosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrosActionPerformed
    CLASSX CD = new CLASSX();
    
    // Obtener la lista de médicos desde la base de datos
    ArrayList<String> medicos = CD.obtenerMedicos();
    
    if (medicos.isEmpty()) {
        JOptionPane.showMessageDialog(null, "No hay médicos registrados.", "Registros", JOptionPane.INFORMATION_MESSAGE);
        return;
    }
    
    // Convertir la lista de médicos en un solo String para mostrarlo en el JOptionPane
    StringBuilder sb = new StringBuilder("Lista de Médicos:\n\n");
    for (String medico : medicos) {
        sb.append(medico).append("\n");
    }
    
    // Mostrar la lista de médicos en un JOptionPane
    JOptionPane.showMessageDialog(null, sb.toString(), "Registros", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_registrosActionPerformed

    
   

    
